def seed_database():
    conn = sqlite3.connect('data/grocery.db')
    c = conn.cursor()

    # Get category mapping
    c.execute("SELECT id, name FROM categories")
    cat_rows = c.fetchall()
    cat_map = {name: cid for cid, name in cat_rows}

    inserted = 0
    now_str = datetime.utcnow().isoformat()

    for cat_name, items in SEEDS.items():
        cid = cat_map.get(cat_name)
        if not cid:
            continue
        for it in items:
            norm = normalize_hebrew_text(it)
            c.execute("""
                INSERT OR REPLACE INTO classifier_cache
                (item_name_normalized, category_id, confidence, source, usage_count, updated_at)
                VALUES (?, ?, 1.0, 'seed', 1, ?)
            """, (norm, cid, now_str))
            inserted += 1

    conn.commit()
    print(f"Successfully seeded {inserted} grocery items into classifier_cache!")

if __name__ == "__main__":
    seed_database()
